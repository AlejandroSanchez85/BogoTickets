/* =====================================================================
   1. CREATE TABLE en orden de dependencia (padres primero)
   ===================================================================== */

-- ESCENARIO ------------------------------------------------------------
CREATE TABLE escenario (
    id_escenario      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre            VARCHAR(100) NOT NULL,
    direccion         VARCHAR(150) NOT NULL,
    capacidad_maxima  INTEGER      NOT NULL,
    CONSTRAINT pk_escenario            PRIMARY KEY (id_escenario),
    CONSTRAINT uq_escenario_nombre     UNIQUE (nombre),
    CONSTRAINT chk_escenario_nombre    CHECK (TRIM(nombre) <> ''),
    CONSTRAINT chk_escenario_direccion CHECK (TRIM(direccion) <> ''),
    CONSTRAINT chk_escenario_capacidad CHECK (capacidad_maxima > 0)         -- RN-03
);

-- LOCALIDAD ------------------------------------------------------------
CREATE TABLE localidad (
    id_localidad  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_escenario  INTEGER     NOT NULL,
    nombre        VARCHAR(50) NOT NULL,
    aforo_maximo  INTEGER     NOT NULL,
    CONSTRAINT pk_localidad PRIMARY KEY (id_localidad),
    CONSTRAINT fk_localidad_escenario FOREIGN KEY (id_escenario)
        REFERENCES escenario (id_escenario)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT uq_localidad_escenario_nombre UNIQUE (id_escenario, nombre),
    CONSTRAINT chk_localidad_nombre CHECK (TRIM(nombre) <> ''),
    CONSTRAINT chk_localidad_aforo  CHECK (aforo_maximo > 0)                -- RN-04
);

-- EVENTO ---------------------------------------------------------------
CREATE TABLE evento (
    id_evento       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_escenario    INTEGER      NOT NULL,                                  -- RN-02
    nombre          VARCHAR(150) NOT NULL,
    fecha           DATE         NOT NULL,
    hora_inicio     TIME         NOT NULL,
    fecha_registro  DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_evento PRIMARY KEY (id_evento),
    CONSTRAINT fk_evento_escenario FOREIGN KEY (id_escenario)
        REFERENCES escenario (id_escenario)
        ON DELETE RESTRICT ON UPDATE CASCADE,                               -- RN-14
    CONSTRAINT uq_evento_escenario_fecha_hora
        UNIQUE (id_escenario, fecha, hora_inicio),                          -- RN-13
    CONSTRAINT chk_evento_nombre         CHECK (TRIM(nombre) <> ''),
    CONSTRAINT chk_evento_fecha          CHECK (fecha >= fecha_registro),   -- RN-11
    CONSTRAINT chk_evento_fecha_registro CHECK (fecha_registro <= CURRENT_DATE)
);

-- PRECIO_LOCALIDAD (tabla intermedia N:M EVENTO - LOCALIDAD) --------------
CREATE TABLE precio_localidad (
    id_evento     INTEGER        NOT NULL,
    id_localidad  INTEGER        NOT NULL,
    precio        NUMERIC(12,2)  NOT NULL,
    CONSTRAINT pk_precio_localidad PRIMARY KEY (id_evento, id_localidad),
    CONSTRAINT fk_precio_evento FOREIGN KEY (id_evento)
        REFERENCES evento (id_evento)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_precio_localidad FOREIGN KEY (id_localidad)
        REFERENCES localidad (id_localidad)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT chk_precio_valor CHECK (precio >= 0)                         -- RN-06
);

-- CLIENTE --------------------------------------------------------------
CREATE TABLE cliente (
    id_cliente       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    documento        VARCHAR(20)  NOT NULL,
    nombre_completo  VARCHAR(120) NOT NULL,
    correo           VARCHAR(120) NOT NULL,
    telefono         VARCHAR(15)  NOT NULL,
    fecha_registro   DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_cliente PRIMARY KEY (id_cliente),
    CONSTRAINT uq_cliente_documento UNIQUE (documento),                     -- RN-09
    CONSTRAINT uq_cliente_correo    UNIQUE (correo),                        -- RN-10
    CONSTRAINT chk_cliente_documento CHECK (documento ~ '^[0-9A-Z]{5,20}$'),
    CONSTRAINT chk_cliente_nombre    CHECK (TRIM(nombre_completo) <> ''),
    CONSTRAINT chk_cliente_correo
        CHECK (correo ~ '^[a-z0-9._%+-]+@[a-z0-9.-]+[.][a-z]{2,}$'),
    CONSTRAINT chk_cliente_telefono  CHECK (telefono ~ '^[0-9]{7,15}$'),
    CONSTRAINT chk_cliente_fecha_registro CHECK (fecha_registro <= CURRENT_DATE)
);

-- BOLETA ---------------------------------------------------------------
-- (id_evento, id_localidad) es una FK COMPUESTA hacia precio_localidad:
-- solo se puede vender una boleta para una localidad que tenga precio
-- asignado en ese evento (RN-08).
CREATE TABLE boleta (
    id_boleta     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente    INTEGER     NOT NULL,
    id_evento     INTEGER     NOT NULL,
    id_localidad  INTEGER     NOT NULL,
    fecha_compra  DATE        NOT NULL DEFAULT CURRENT_DATE,
    estado        VARCHAR(10) NOT NULL DEFAULT 'Vendida',
    CONSTRAINT pk_boleta PRIMARY KEY (id_boleta),
    CONSTRAINT fk_boleta_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_boleta_precio_localidad FOREIGN KEY (id_evento, id_localidad)
        REFERENCES precio_localidad (id_evento, id_localidad)
        ON DELETE RESTRICT ON UPDATE RESTRICT,                              -- RN-14
    CONSTRAINT chk_boleta_estado CHECK (estado IN ('Vendida', 'Cancelada')), -- RNF-07
    CONSTRAINT chk_boleta_fecha  CHECK (fecha_compra <= CURRENT_DATE)        -- RNF-03
);

-- HISTORIAL_PRECIOS (auditoría, RNF-06) ----------------------------------
-- campo_modificado = 'PRECIO'       -> id_evento obligatorio (el precio es por evento y localidad)
-- campo_modificado = 'AFORO_MAXIMO' -> id_evento NULL (el aforo es propio de la localidad)
CREATE TABLE historial_precios (
    id_historial      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_localidad      INTEGER       NOT NULL,
    id_evento         INTEGER,
    campo_modificado  VARCHAR(20)   NOT NULL,
    valor_anterior    NUMERIC(12,2) NOT NULL,
    valor_nuevo       NUMERIC(12,2) NOT NULL,
    usuario           VARCHAR(50)   NOT NULL DEFAULT CURRENT_USER,
    fecha_cambio      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_historial_precios PRIMARY KEY (id_historial),
    CONSTRAINT fk_historial_localidad FOREIGN KEY (id_localidad)
        REFERENCES localidad (id_localidad)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_historial_evento FOREIGN KEY (id_evento)
        REFERENCES evento (id_evento)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_historial_campo
        CHECK (campo_modificado IN ('PRECIO', 'AFORO_MAXIMO')),
    CONSTRAINT chk_historial_coherencia CHECK (
        (campo_modificado = 'PRECIO'       AND id_evento IS NOT NULL) OR
        (campo_modificado = 'AFORO_MAXIMO' AND id_evento IS NULL)),
    CONSTRAINT chk_historial_valores CHECK (valor_anterior >= 0 AND valor_nuevo >= 0),
    CONSTRAINT chk_historial_usuario CHECK (TRIM(usuario) <> '')
);

